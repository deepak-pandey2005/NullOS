//! CPU Control Registers, Hardware Defenses & Silicon Feature Management.
//!
//! # Overview
//! Direct management of x86_64 architectural control registers and Model-Specific
//! Registers (MSRs) to activate hardware-enforced CPU security and instruction sets:
//! - **CR0.WP (Bit 16)**: Write Protect. Prevents the kernel (Ring 0) from writing to
//!   user- or kernel-mode pages marked read-only in the page table hierarchy.
//! - **EFER.NXE (Bit 11)**: No-Execute Enable. Enables the 63rd bit (NX/XD) in 4-level
//!   paging entries to prevent malicious code execution in stack, heap, or MMIO buffers.
//! - **CR4.PGE (Bit 7)**: Page Global Enable. Preserves global page translations across
//!   address space context switches (`CR3` reloads), drastically reducing TLB misses.
//! - **CR4.OSFXSR (Bit 9)**: OS FXSAVE/FXRSTOR Support. Enables hardware floating point
//!   and 128-bit/256-bit SIMD registers (`%xmm0..%xmm15`).
//! - **CR4.OSXMMEXCPT (Bit 10)**: OS Unmasked Exception Support for SIMD floating point faults.
//! - **CR4.SMEP (Bit 20)**: Supervisor Mode Execution Prevention. Silicon fault (#PF)
//!   if Ring 0 attempts to execute instructions from user-accessible virtual pages.
//! - **CR4.SMAP (Bit 21)**: Supervisor Mode Access Prevention. Silicon fault (#PF)
//!   if Ring 0 attempts to read/write user-space memory without explicit `stac` authorization.

#![allow(dead_code)]

use crate::println;

/// IA32_EFER Model-Specific Register (Extended Feature Enable Register).
const IA32_EFER_MSR: u32 = 0xC000_0080;

/// Executes the x86 `cpuid` instruction for a specific leaf and subleaf.
///
/// Preserves `%rbx` on the stack to prevent clobbering the System V AMD64 callee-saved register
/// or position-independent base register.
///
/// # Returns
/// A 4-tuple `(eax, ebx, ecx, edx)` populated with hardware feature flags and CPU vendor strings.
#[inline]
pub fn cpuid(leaf: u32, subleaf: u32) -> (u32, u32, u32, u32) {
    let mut eax: u32;
    let ebx: u32;
    let mut ecx: u32;
    let edx: u32;
    unsafe {
        core::arch::asm!(
            "push rbx",
            "cpuid",
            "mov {tmp:e}, ebx",
            "pop rbx",
            inout("eax") leaf => eax,
            inout("ecx") subleaf => ecx,
            tmp = out(reg) ebx,
            out("edx") edx,
            options(nomem)
        );
    }
    (eax, ebx, ecx, edx)
}

/// Temporarily enables supervisor mode access to user memory (sets `RFLAGS.AC = 1`).
///
/// Used exclusively inside bounded memory transfer guards (`copy_from_user`, `copy_to_user`)
/// when SMAP is active.
///
/// # Safety
/// Caller must ensure that user buffers are pre-validated and that `clac()` is immediately
/// executed when the transfer completes to close the privilege window.
#[inline(always)]
pub unsafe fn stac() {
    unsafe {
        core::arch::asm!("stac", options(nomem, nostack));
    }
}

/// Disables supervisor mode access to user memory (clears `RFLAGS.AC = 0`).
///
/// Re-arms SMAP protection to trap any accidental supervisor read/write into user addresses.
#[inline(always)]
pub unsafe fn clac() {
    unsafe {
        core::arch::asm!("clac", options(nomem, nostack));
    }
}

/// Returns whether CR0 Write Protection (`CR0.WP`, bit 16) is active.
#[inline]
pub fn is_wp_enabled() -> bool {
    (read_cr0() & (1 << 16)) != 0
}

/// Returns whether No-Execute memory protection (`EFER.NXE`, bit 11) is active.
#[inline]
pub fn is_nxe_enabled() -> bool {
    unsafe { (read_msr(IA32_EFER_MSR) & (1 << 11)) != 0 }
}

/// Returns whether Supervisor Mode Execution Prevention (`CR4.SMEP`, bit 20) is active.
#[inline]
pub fn is_smep_enabled() -> bool {
    (read_cr4() & (1 << 20)) != 0
}

/// Returns whether Supervisor Mode Access Prevention (`CR4.SMAP`, bit 21) is active.
#[inline]
pub fn is_smap_enabled() -> bool {
    (read_cr4() & (1 << 21)) != 0
}

/// Reads a 64-bit Model-Specific Register (MSR) using the `rdmsr` instruction.
///
/// # Safety
/// The requested MSR index must exist on the physical CPU, otherwise a General Protection
/// Fault (`#GP`) will be generated by the processor.
#[inline]
unsafe fn read_msr(msr: u32) -> u64 {
    let low: u32;
    let high: u32;
    unsafe {
        core::arch::asm!("rdmsr", in("ecx") msr, out("eax") low, out("edx") high, options(nomem, nostack));
    }
    ((high as u64) << 32) | (low as u64)
}

/// Writes a 64-bit value to a Model-Specific Register (MSR) using `wrmsr`.
///
/// # Safety
/// The requested MSR must be supported and the value must conform to architectural limits.
#[inline]
unsafe fn write_msr(msr: u32, val: u64) {
    let low = val as u32;
    let high = (val >> 32) as u32;
    unsafe {
        core::arch::asm!("wrmsr", in("ecx") msr, in("eax") low, in("edx") high, options(nomem, nostack));
    }
}

/// Reads the current value of the `CR0` Control Register.
#[inline]
pub fn read_cr0() -> u64 {
    let val: u64;
    unsafe {
        core::arch::asm!("mov {}, cr0", out(reg) val, options(nomem, nostack));
    }
    val
}

/// Writes a 64-bit value to the `CR0` Control Register.
#[inline]
unsafe fn write_cr0(val: u64) {
    unsafe {
        core::arch::asm!("mov cr0, {}", in(reg) val, options(nomem, nostack));
    }
}

/// Reads the current value of the `CR4` Control Register.
#[inline]
pub fn read_cr4() -> u64 {
    let val: u64;
    unsafe {
        core::arch::asm!("mov {}, cr4", out(reg) val, options(nomem, nostack));
    }
    val
}

/// Writes a 64-bit value to the `CR4` Control Register.
#[inline]
unsafe fn write_cr4(val: u64) {
    unsafe {
        core::arch::asm!("mov cr4, {}", in(reg) val, options(nomem, nostack));
    }
}

/// Initializes modern x86_64 CPU hardware features, SIMD capabilities, and security flags.
///
/// # Configuration Steps
/// 1. **CR0 Configuration**:
///    - `MP` (Bit 1): Monitor Coprocessor. Enables `WAIT`/`FWAIT` instruction monitoring.
///    - `EM` (Bit 2): Cleared to 0 to prevent emulation trap (`#UD`) on x87/SSE instructions.
///    - `TS` (Bit 3): Cleared to 0 to prevent Task-Switched trap (`#NM`) on SIMD operations.
///    - `WP` (Bit 16): Write Protect. Enforces page-table read-only permissions in Ring 0.
/// 2. **EFER.NXE Configuration**:
///    - Activates Bit 11 of `IA32_EFER`, enabling the No-Execute page protection flag.
/// 3. **CR4 Configuration**:
///    - `PGE` (Bit 7): Page Global Enable for TLB performance.
///    - `OSFXSR` (Bit 9): Enables hardware saving/restoring of SSE/AVX registers.
///    - `OSXMMEXCPT` (Bit 10): Enables CPU delivery of unmasked SIMD floating-point exceptions (#XM).
/// 4. **CPUID Feature Probing & SMEP**:
///    - Queries CPUID Leaf 7 Subleaf 0 for SMEP (`ebx & (1 << 7)`) and SMAP (`ebx & (1 << 20)`).
///    - Activates SMEP in `CR4` if silicon support is present.
pub fn init() {
    unsafe {
        // Step 1: Configure CR0 control flags
        let mut cr0 = read_cr0();
        cr0 |= (1 << 16) | (1 << 1); // Enable WP (Write Protect) and MP (Monitor Coprocessor)
        cr0 &= !(1 << 2);            // Clear EM (prevents #UD on FPU/SSE/AVX)
        cr0 &= !(1 << 3);            // Clear TS (prevents #NM on FPU/SSE/AVX)
        write_cr0(cr0);

        // Step 2: Enable EFER.NXE (Bit 11 - No-Execute / Execute-Disable Enable)
        let efer = read_msr(IA32_EFER_MSR);
        let nxe_flag = 1 << 11;
        if (efer & nxe_flag) == 0 {
            write_msr(IA32_EFER_MSR, efer | nxe_flag);
        }

        // Step 3: Enable CR4 performance & SIMD features
        let mut cr4 = read_cr4();
        cr4 |= (1 << 7) | (1 << 9) | (1 << 10);

        // Step 4: Query Extended Features via CPUID Leaf 7 Subleaf 0
        let (max_leaf, _, _, _) = cpuid(0, 0);
        let mut smep_supported = false;
        let mut smap_supported = false;

        if max_leaf >= 7 {
            let (_, ebx, _, _) = cpuid(7, 0);
            smep_supported = (ebx & (1 << 7)) != 0;
            smap_supported = (ebx & (1 << 20)) != 0;
        }

        // Enable SMEP (Supervisor Mode Execution Prevention, Bit 20 in CR4) if supported
        if smep_supported {
            cr4 |= 1 << 20;
        }

        write_cr4(cr4);

        println!(
            "[CPU] Modern CPU features activated: CR0.WP, EFER.NXE, CR4.PGE, CR4.OSFXSR (SMEP: {}, SMAP: {}).",
            if smep_supported { "Enabled" } else { "Unsupported" },
            if smap_supported { "Supported" } else { "Unsupported" }
        );
    }
}
